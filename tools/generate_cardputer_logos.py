"""Compile the original Cardputer logos into flash pixels; no runtime PNG heap.

The originals remain unchanged. Match the established UI render areas and
Lanczos preview scaling, composite alpha on the existing background, then
quantize to RGB565. The RGB332 framebuffer retains the same top color bits.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "include/cardputer_logo_pixels.h"
SPECS = (
    ("radio", "lora-tunnel-radio-logo.png", 74, 74, (0, 4, 8)),
    ("vts", "vts-official-logo.png", 19, 20, (255, 255, 255)),
)


def logo_pixels(filename: str, width: int, height: int, background: tuple[int, int, int]) -> list[int]:
    with Image.open(ROOT / "assets" / filename) as original:
        source = original.convert("RGBA")
    source.thumbnail((width, height), Image.Resampling.LANCZOS)
    target = Image.new("RGB", (width, height), background)
    target.paste(source, (0, 0), source)
    return [((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
            for red, green, blue in target.getdata()]


def generated_header() -> str:
    lines = ["#pragma once", "", "// Generated by tools/generate_cardputer_logos.py; do not edit by hand.",
             "// Original artwork is unchanged. RGB565 constants live in flash; no PNG decoder or logo heap.",
             "#include <cstdint>", "", "namespace cardputer_assets {"]
    for name, filename, width, height, background in SPECS:
        digest = hashlib.sha256((ROOT / "assets" / filename).read_bytes()).hexdigest()
        values = logo_pixels(filename, width, height, background)
        lines.extend((f"// Source: assets/{filename} SHA-256: {digest}",
                      f"constexpr unsigned {name}Width = {width}, {name}Height = {height};",
                      f"static constexpr std::uint16_t {name}Pixels[{width * height}] = {{"))
        for offset in range(0, len(values), 16):
            lines.append("  " + ", ".join(f"0x{value:04x}" for value in values[offset:offset + 16]) + ",")
        lines.extend(("};", ""))
    lines.extend(("} // namespace cardputer_assets", ""))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when committed pixels differ from original artwork")
    args = parser.parse_args()
    expected = generated_header()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Cardputer logo pixels are stale; run tools/generate_cardputer_logos.py\n")
        print("Cardputer logo pixels match original artwork; 11712 flash bytes, no runtime decoder")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
